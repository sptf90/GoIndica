ALTER TABLE profiles ADD COLUMN photo_updated_at DATETIME(3) NULL;
CREATE TABLE profile_photos (
 profile_id CHAR(36) PRIMARY KEY, jpeg MEDIUMBLOB NOT NULL,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(profile_id) REFERENCES profiles(id), CHECK(OCTET_LENGTH(jpeg) BETWEEN 4 AND 524288)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
