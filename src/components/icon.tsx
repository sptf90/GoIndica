import {
  ArrowRight,
  ArrowUpRight,
  Award,
  Bell,
  Bookmark,
  Calendar,
  Camera,
  Check,
  ChevronDown,
  ChevronLeft,
  ClipboardList,
  Clock,
  Command,
  Compass,
  Eye,
  EyeOff,
  Flame,
  LogOut,
  Map as MapIcon,
  MapPin,
  Menu,
  MessageCircle,
  PenLine,
  Plus,
  Search,
  Share,
  ShieldCheck,
  SlidersHorizontal,
  Sparkles,
  Trophy,
  UserRound,
  Users,
  X,
  type LucideIcon,
} from 'lucide-react';

const icons = {
  share: Share,
  camera: Camera,
  eye: Eye,
  eyeClosed: EyeOff,
  plus: Plus,
  arrow: ArrowRight,
  external: ArrowUpRight,
  bookmark: Bookmark,
  person: UserRound,
  activity: ClipboardList,
  award: Award,
  trophy: Trophy,
  flame: Flame,
  message: MessageCircle,
  check: Check,
  shield: ShieldCheck,
  settings: SlidersHorizontal,
  bell: Bell,
  compass: Compass,
  chevron: ChevronDown,
  menu: Menu,
  close: X,
  back: ChevronLeft,
  calendar: Calendar,
  edit: PenLine,
  pin: MapPin,
  users: Users,
  map: MapIcon,
  search: Search,
  clock: Clock,
  sparkle: Sparkles,
  command: Command,
  logout: LogOut,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof icons;

export function Icon({ name, size = 20 }: { name: IconName; size?: number }) {
  const Glyph = icons[name];
  return (
    <Glyph size={size} strokeWidth={1.75} aria-hidden="true" focusable="false" className="icon" />
  );
}
